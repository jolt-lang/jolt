;; Regenerates host/chez/java/jdk-interfaces.ss: every public interface (an
;; annotation type is one) in the JDK's java.* and javax.* packages, and in the
;; com.sun.* and jdk.* packages a module exports to everyone (the supported
;; API: com.sun.net.httpserver, jdk.jfr, …, not the internals), every module,
;; read off the JDK it runs on.
;;
;;   JAVA_CMD=/opt/homebrew/opt/openjdk@21/bin/java clojure -M tools/gen-jdk-interfaces.clj
;;
;; Run it on the JDK the conformance oracle is pinned to (test/conformance/profile.edn).
(import '[java.nio.file FileSystems Files Path] '[java.net URI] '[java.lang.module ModuleFinder])
(def fs (FileSystems/getFileSystem (URI. "jrt:/")))
(def root (.getPath fs "/modules" (make-array String 0)))
(def exported
  (set (for [m (.findAll (ModuleFinder/ofSystem))
             e (.exports (.descriptor m))
             :when (not (.isQualified e))]
         (.source e))))
(defn- package-of [^String n] (let [i (.lastIndexOf n ".")] (if (neg? i) "" (subs n 0 i))))
(defn- api? [^String n]
  (or (.startsWith n "java.") (.startsWith n "javax.")
      (and (or (.startsWith n "com.sun.") (.startsWith n "jdk."))
           (contains? exported (package-of n)))))
(def names
  (with-open [s (Files/walk root (make-array java.nio.file.FileVisitOption 0))]
    (->> (iterator-seq (.iterator s))
         (map str)
         (filter #(and (.endsWith ^String % ".class") (not (.contains ^String % "module-info"))))
         (map #(let [p (subs % (count "/modules/"))] (-> p (subs (inc (.indexOf p "/"))) (.replace ".class" "") (.replace "/" "."))))
         (filter api?)
         doall)))
(def ifs (sort (for [n names
                     :let [c (try (Class/forName n false (ClassLoader/getSystemClassLoader)) (catch Throwable _ nil))]
                     :when (and c (.isInterface c) (java.lang.reflect.Modifier/isPublic (.getModifiers c)))]
                 n)))
(spit "host/chez/java/jdk-interfaces.ss"
  (str ";; GENERATED by tools/gen-jdk-interfaces.clj from JDK " (System/getProperty "java.version") " — do not edit.\n"
       ";; Every public interface in the JDK's java.* / javax.* packages, and in the com.sun.* / jdk.*\n"
       ";; packages exported to everyone. A JDK name the class graph does not\n"
       ";; model is an interface when it is here and a class otherwise\n"
       ";; (class-hierarchy.ss jch-interface? / jch-jdk-class?).\n"
       "(define jdk-public-interfaces\n  (let ((t (make-hashtable string-hash string=?)))\n    (for-each (lambda (n) (hashtable-set! t n #t))\n      '(\n"
       (clojure.string/join "\n" (map #(str "        \"" % "\"") ifs))
       "))\n    t))\n"))
(println "wrote" (count ifs) "interfaces")
